I18N.switchLang=function(lang){
  if(!lang)lang=I18N.current==='ru'?'en':'ru';
  I18N.current=lang;
  localStorage.setItem('lenin-lang',lang);
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key=el.getAttribute('data-i18n');
    if(I18N.t[key]&&I18N.t[key][lang]){
      if(el.tagName==='INPUT'||el.tagName==='TEXTAREA')el.placeholder=I18N.t[key][lang];
      else el.innerHTML=I18N.t[key][lang];
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
    var key=el.getAttribute('data-i18n-placeholder');
    if(I18N.t[key]&&I18N.t[key][lang])el.placeholder=I18N.t[key][lang];
  });
  var btn=document.getElementById('lang-toggle-btn');
  if(btn)btn.textContent=I18N.t['lang-toggle'][lang==='ru'?'en':'ru']||(lang==='ru'?'EN':'RU');
  document.documentElement.lang=lang;
};

I18N.init=function(){
  var saved=localStorage.getItem('lenin-lang');
  if(saved&&(saved==='ru'||saved==='en'))I18N.current=saved;
  I18N.switchLang(I18N.current);
};
