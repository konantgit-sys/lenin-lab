# Авто-генерация ключевых слов для дополнительных тем
def auto_keywords(topic: str) -> list:
    """Генерирует ключевые слова для темы."""
    base = topic.lower()
    kws = [base]
    # Вариации
    if base.endswith("изм"):
        kws.append(base[:-3] + "ист")
        kws.append(base[:-3] + "исты")
        kws.append(base[:-3] + "истическ")
    elif base.endswith("ство"):
        kws.append(base[:-4] + "ский")
    return kws


