def build_cooccurrence_graph():
    """
    Строит граф совместной встречаемости концептов.
    Сканирует все 169K параграфов, считает co-occurrence.
    Возвращает networkx.Graph + статистику.
    Кешируется в модуле для повторных вызовов.
    """
    global _cached_graph, _cached_concept_count

    if _cached_graph is not None:
        return _cached_graph, _cached_concept_count, None  # None for paragraphs (not needed after cache)

    conn = get_connection()

    # Шаг 1: Собираем корпус параграфов (все)
    paragraphs = conn.execute(
        "SELECT id, text, year FROM paragraphs WHERE year IS NOT NULL ORDER BY id"
    ).fetchall()

    # Шаг 2: Строим co-occurrence матрицу
    cooc = defaultdict(lambda: defaultdict(int))
    concept_count = defaultdict(int)

    for pid, text, year in paragraphs:
        if not text:
            continue
        text_lower = text.lower()

        # Находим все концепты в этом параграфе
        found = set()
        for concept, keywords in CONCEPTS.items():
            if any(kw in text_lower for kw in keywords):
                found.add(concept)
                concept_count[concept] += 1

        # Добавляем рёбра между всеми найденными парами
        found_list = list(found)
        for i in range(len(found_list)):
            for j in range(i + 1, len(found_list)):
                a, b = found_list[i], found_list[j]
                if a < b:
                    cooc[a][b] += 1
                else:
                    cooc[b][a] += 1

    conn.close()

    # Шаг 3: Строим граф networkx
    G = nx.Graph()

    # Добавляем узлы (только те концепты, что реально найдены)
    for concept in CONCEPTS:
        count = concept_count.get(concept, 0)
        if count > 0:
            G.add_node(concept, count=count)
        else:
            G.add_node(concept, count=0)  # изолированный узел

    # Добавляем рёбра
    for a, inner in cooc.items():
        for b, weight in inner.items():
            if a in G and b in G and weight > 0:
                G.add_edge(a, b, weight=weight)

    _cached_graph = G
    _cached_concept_count = concept_count
    return G, concept_count, paragraphs


def compute_clusters(G):
    """Louvain community detection с подбором resolution для 8-12 кластеров."""
    # Применяем к largest connected component чтобы избежать проблем с изолятами
    if nx.is_connected(G):
        working_graph = G
    else:
        largest_cc = max(nx.connected_components(G), key=len)
        working_graph = G.subgraph(largest_cc)

    # Ищем resolution, дающий 8-12 кластеров
    for resolution in [0.5, 0.6, 0.7, 0.75, 0.8, 0.85, 0.9, 0.95, 1.0, 1.1, 1.2, 1.3, 1.5, 2.0]:
        communities = louvain_communities(working_graph, weight='weight', resolution=resolution, seed=42)
        n_clusters = len(communities)
        if 8 <= n_clusters <= 12:
            break
    else:
        # Если не нашли, берём resolution=1
        communities = louvain_communities(working_graph, weight='weight', resolution=1, seed=42)

    # Сортируем кластеры по размеру
    communities = sorted(communities, key=len, reverse=True)

    return communities


def name_clusters(communities, G):
    """Даёт имена кластерам на основе топ-концептов."""
    cluster_names = []
    name_counts = {}

    for comm in communities:
        best_name = "Смешанный"
        best_overlap = 0
        for expected_name, expected_concepts in EXPECTED_CLUSTERS.items():
            overlap = len(set(comm) & set(expected_concepts))
            if overlap > best_overlap:
                best_overlap = overlap
                best_name = expected_name

        # Дедупликация имён
        if best_name in name_counts:
            name_counts[best_name] += 1
            cluster_names.append(f"{best_name} {name_counts[best_name]}")
        else:
            name_counts[best_name] = 1
            cluster_names.append(best_name)

    return cluster_names


def get_concept_graph():
    """Основная функция — возвращает полный граф для API."""
    G, concept_count, _ = build_cooccurrence_graph()
    communities = compute_clusters(G)
    cluster_names = name_clusters(communities, G)

    # Узлы
    nodes = []
    for node, data in G.nodes(data=True):
        # Определяем кластер узла
        node_cluster = None
        for i, comm in enumerate(communities):
            if node in comm:
                node_cluster = i
                break
        nodes.append({
            "id": node,
            "count": data.get("count", 0),
            "cluster": node_cluster,
            "cluster_name": cluster_names[node_cluster] if node_cluster is not None else "Изолированный",
        })

    # Рёбра (топ-100 по весу)
    edges = []
    for u, v, data in G.edges(data=True):
        edges.append({
            "source": u,
            "target": v,
            "weight": data.get("weight", 0),
        })
    edges.sort(key=lambda e: e["weight"], reverse=True)
    edges = edges[:100]

    # Статистика
    connected_nodes = sum(1 for n in G.nodes if G.degree(n) > 0)
    isolated = G.number_of_nodes() - connected_nodes

    result = {
        "nodes": G.number_of_nodes(),
        "edges_total": G.number_of_edges(),
        "edges_shown": len(edges),
        "clusters": len(communities),
        "cluster_names": cluster_names,
        "connected_nodes": connected_nodes,
        "isolated_nodes": isolated,
        "nodes_data": nodes,
        "top_edges": edges,
    }

    return result


def get_concept_evolution(concept: str):
    """Эволюция концепта по годам."""
    if concept not in CONCEPTS:
        return {"error": f"Concept '{concept}' not found"}

    conn = get_connection()
    keywords = CONCEPTS[concept]

    evolution = {}
    for row in conn.execute(
        "SELECT year, COUNT(*) as cnt FROM paragraphs WHERE year IS NOT NULL GROUP BY year ORDER BY year"
    ):
        year = row[0]
        # Считаем для каждого года количество вхождений
        query = "SELECT COUNT(*) FROM paragraphs WHERE year = ? AND ("
        query += " OR ".join(["text LIKE '%' || ? || '%'" for _ in keywords])
        query += ")"
        params = [year] + keywords
        cnt = conn.execute(query, params).fetchone()[0]
        if cnt > 0:
            evolution[str(year)] = cnt

    conn.close()

    return {
        "concept": concept,
        "keywords": keywords[:5],
        "by_year": evolution,
        "total_occurrences": sum(evolution.values()),
        "peak_year": max(evolution, key=evolution.get) if evolution else None,
    }


