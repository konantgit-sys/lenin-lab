def get_connection():
    return sqlite3.connect(str(DB_PATH))


def create_comparative_table(conn):
    conn.execute("""
        CREATE TABLE IF NOT EXISTS lenin_comparative (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            topic TEXT NOT NULL UNIQUE,
            marx_position TEXT,
            engels_position TEXT,
            lenin_position TEXT,
            lenin_year INTEGER,
            lenin_volume INTEGER,
            evolution TEXT,
            divergence TEXT,
            source TEXT
        )
    """)
    conn.execute("CREATE INDEX IF NOT EXISTS idx_comparative_topic ON lenin_comparative(topic)")
    conn.commit()


def get_lenin_position(conn, topic: str) -> dict:
    """Получает лучшую цитату Ленина по теме (case-insensitive)."""
    row = conn.execute(
        """SELECT text, year, volume_id FROM lenin_positions
           WHERE LOWER(topic) = LOWER(?) AND rank = 1
           ORDER BY relevance_score DESC LIMIT 1""",
        (topic,),
    ).fetchone()
    if row:
        return {"text": row[0][:400], "year": row[1], "volume": row[2]}
    return None


def get_mentions_of_classics(conn, topic: str) -> dict:
    """Находит упоминания Маркса/Энгельса в контексте темы."""
    marx_mentions = conn.execute(
        """SELECT COUNT(*) FROM paragraphs
           WHERE (text LIKE '%Маркс%' OR text LIKE '%Маркса%')
           AND text LIKE ? LIMIT 1""",
        (f"%{topic}%",),
    ).fetchone()[0]

    engels_mentions = conn.execute(
        """SELECT COUNT(*) FROM paragraphs
           WHERE (text LIKE '%Энгельс%')
           AND text LIKE ? LIMIT 1""",
        (f"%{topic}%",),
    ).fetchone()[0]

    return {"marx_mentions": marx_mentions, "engels_mentions": engels_mentions}


def analyze_evolution(topic: str, marx_pos: str, lenin_pos: dict) -> str:
    """Анализирует эволюцию мысли от Маркса к Ленину."""
    if not lenin_pos:
        return "Ленинская позиция не найдена"

    # Эвристики эволюции
    l_text = lenin_pos["text"].lower()
    l_year = lenin_pos["year"]

    if l_year and l_year >= 1914 and "империализм" in l_text:
        return "Развитие: Ленин применил марксистскую теорию к эпохе империализма, добавив анализ монополий и финансового капитала"
    elif l_year and l_year >= 1917 and "совет" in l_text:
        return "Конкретизация: Ленин наполнил марксистскую теорию практическим содержанием — Советы как форма диктатуры пролетариата"
    elif l_year and l_year <= 1905:
        return "Адаптация: Ленин применил марксизм к российским условиям — аграрный вопрос, самодержавие, крестьянство"
    elif "партия" in l_text and "профессиональн" in l_text:
        return "Развитие: Ленин разработал учение о партии нового типа — авангард, а не массовая организация"
    else:
        return "Развитие: Ленин конкретизировал и применил марксистскую теорию к российской действительности"


def build_comparative_catalog():
    """Строит сравнительный каталог."""
    conn = get_connection()
    create_comparative_table(conn)

    # Находим пересечение: темы, которые есть и у классиков, и у Ленина
    lenin_topics = set(
        r[0] for r in conn.execute("SELECT DISTINCT topic FROM lenin_positions").fetchall()
    )

    common_topics = [t for t in MARXIST_BASIS if t in lenin_topics]
    print(f"Common topics: {len(common_topics)}")

    conn.execute("DELETE FROM lenin_comparative")
    inserted = 0

    for topic in common_topics:
        basis = MARXIST_BASIS[topic]
        lenin = get_lenin_position(conn, topic)
        mentions = get_mentions_of_classics(conn, topic)
        evolution = analyze_evolution(topic, basis["marx"], lenin)

        conn.execute(
            """INSERT INTO lenin_comparative (topic, marx_position, engels_position, lenin_position, lenin_year, lenin_volume, evolution, divergence, source)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            (
                topic,
                basis["marx"],
                basis["engels"],
                lenin["text"] if lenin else None,
                lenin["year"] if lenin else None,
                lenin["volume"] if lenin else None,
                evolution,
                "",  # divergence — заполняется вручную
                basis["source"],
            ),
        )
        inserted += 1

    conn.commit()

    # Статистика
    total = conn.execute("SELECT COUNT(*) FROM lenin_comparative").fetchone()[0]
    years = conn.execute(
        "SELECT lenin_year, COUNT(*) FROM lenin_comparative WHERE lenin_year IS NOT NULL GROUP BY lenin_year ORDER BY COUNT(*) DESC LIMIT 5"
    ).fetchall()

    conn.close()
    return {"total_comparisons": total, "top_years": [{"year": y, "count": c} for y, c in years]}


def search_comparison(topic: str) -> dict:
    """Поиск сравнения по теме."""
    conn = get_connection()
    row = conn.execute(
        """SELECT topic, marx_position, engels_position, lenin_position, lenin_year, lenin_volume, evolution, source
           FROM lenin_comparative WHERE topic = ?""",
        (topic,),
    ).fetchone()
    conn.close()
    if row:
        return {
            "topic": row[0],
            "marx": row[1],
            "engels": row[2],
            "lenin": row[3],
            "lenin_year": row[4],
            "lenin_volume": row[5],
            "evolution": row[6],
            "source": row[7],
        }
    return None


def list_comparisons():
    conn = get_connection()
    rows = conn.execute("SELECT topic, lenin_year FROM lenin_comparative ORDER BY topic").fetchall()
    conn.close()
    return [{"topic": r[0], "lenin_year": r[1]} for r in rows]


if __name__ == "__main__":
    import sys

    if len(sys.argv) > 1:
        cmd = sys.argv[1]
        if cmd == "--build":
            print("Building comparative catalog...")
            start = time.time()
            result = build_comparative_catalog()
